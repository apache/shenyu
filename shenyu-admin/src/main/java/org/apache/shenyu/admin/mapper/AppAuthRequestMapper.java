package org.apache.shenyu.admin.mapper;

import org.apache.ibatis.annotations.Mapper;
import org.apache.ibatis.annotations.Param;
import org.apache.shenyu.admin.model.entity.AppAuthRequestDO;

import java.util.List;

/**
 * AppAuthRequestMapper.
 * Lock order convention: idempotency key -> app_auth -> param/path; values always bound with #{}.
 */
@Mapper
public interface AppAuthRequestMapper {

    /**
     * Reserve the idempotency key: on unique-key conflict only the existing row id is
     * assigned to the candidate.
     *
     * <p>hash/authId/state are never overwritten.
     *
     * @param candidate candidate record (UUID generated by the caller)
     * @return affected rows
     */
    int reserveIfAbsent(AppAuthRequestDO candidate);

    /**
     * Lock the row for the unique key (SELECT ... FOR UPDATE).
     *
     * @param callerKey caller key
     * @param namespaceId namespace
     * @param requestId request id
     * @return the locked row or null
     */
    AppAuthRequestDO selectByKeyForUpdate(@Param("callerKey") String callerKey,
                                             @Param("namespaceId") String namespaceId,
                                             @Param("requestId") String requestId);

    /**
     * Query by key without locking.
     *
     * @param callerKey caller key
     * @param namespaceId namespace
     * @param requestId request id
     * @return the record or null
     */
    AppAuthRequestDO selectByKey(@Param("callerKey") String callerKey,
                                    @Param("namespaceId") String namespaceId,
                                    @Param("requestId") String requestId);

    /**
     * Query the associated record by app_auth id.
     *
     * @param authId auth id
     * @return the record or null
     */
    AppAuthRequestDO selectByAuthId(@Param("authId") String authId);

    /**
     * Query by a set of auth ids for subsequent per-key locking (stable ordering).
     *
     * @param authIds auth ids
     * @return the associated records in stable order
     */
    List<AppAuthRequestDO> selectKeysByAuthIds(@Param("authIds") List<String> authIds);

    /**
     * Backfill the auth id after reservation (CAS: only when state='CREATED' and auth_id is empty).
     *
     * @param id record id
     * @param authId created auth id
     * @return affected rows (must be 1)
     */
    int completeCreated(@Param("id") String id, @Param("authId") String authId);

    /**
     * Mark REVOKED (historical authId and hash are kept).
     *
     * @param id record id
     * @param reason revoke reason
     * @return affected rows
     */
    int markRevoked(@Param("id") String id, @Param("reason") String reason);
}
